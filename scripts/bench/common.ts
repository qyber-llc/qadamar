import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { SCHEMA } from '../../packages/pdp-http/src/postgres.ts';

export interface Ref { type: string; id: string }
export interface BenchSubject extends Ref { type: 'user' }
export interface BenchResource extends Ref { type: 'case'; owner?: string }
export interface BenchTuple { object: BenchResource; relation: string; subject: BenchSubject; grantedBy?: string; reason?: string }
export interface BenchWorld {
  generator?: string;
  subjects: BenchSubject[];
  resources: BenchResource[];
  tuples: BenchTuple[];
}

export function options(args = process.argv.slice(2)): Map<string, string> {
  const result = new Map<string, string>();
  for (let i = 0; i < args.length; i++) {
    const arg = args[i]!;
    if (!arg.startsWith('--')) throw new Error(`Unexpected argument: ${arg}`);
    const equals = arg.indexOf('=');
    if (equals >= 0) result.set(arg.slice(2, equals), arg.slice(equals + 1));
    else {
      const value = args[++i];
      if (value === undefined) throw new Error(`Missing value for ${arg}`);
      result.set(arg.slice(2), value);
    }
  }
  return result;
}

export function textOption(args: Map<string, string>, name: string, fallback?: string): string {
  const value = args.get(name) ?? fallback;
  if (value === undefined || value === '') throw new Error(`--${name} is required`);
  return value;
}

export function intOption(args: Map<string, string>, name: string, fallback: number, minimum = 1): number {
  const value = Number(args.get(name) ?? fallback);
  if (!Number.isSafeInteger(value) || value < minimum) throw new Error(`--${name} must be an integer >= ${minimum}`);
  return value;
}

export function random(seed: number): () => number {
  let state = seed >>> 0;
  return (): number => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

export function commandLine(): string {
  return process.argv.map((part) => /^[a-zA-Z0-9_./:=+-]+$/.test(part) ? part : `'${part.replaceAll("'", `'\\''`)}'`).join(' ');
}

export function readWorld(directory: string): BenchWorld {
  const world = JSON.parse(readFileSync(`${directory}/world.json`, 'utf8')) as BenchWorld;
  if (world.generator !== 'scripts/bench/world.ts') throw new Error('The world must be generated by scripts/bench/world.ts');
  if (!world.subjects.length || !world.resources.length || !world.tuples.length) throw new Error('The benchmark world must not be empty');
  if (!world.tuples.every((t) => t.relation === 'allocated' && t.object.type === 'case' && t.subject.type === 'user')) {
    throw new Error('The benchmark world has an unexpected relation shape');
  }
  return world;
}

export function evaluation(tuple: BenchTuple): Record<string, unknown> {
  return {
    subject: { type: tuple.subject.type, id: tuple.subject.id },
    action: { name: 'read' },
    resource: { type: tuple.object.type, id: tuple.object.id },
    context: { network: 'trusted' },
  };
}

export interface Memory {
  rssBytes: number;
  heapUsedBytes: number;
}
export function memory(): Memory {
  const value = process.memoryUsage();
  return { rssBytes: value.rss, heapUsedBytes: value.heapUsed };
}

export interface HttpResult {
  status: number;
  latencyMs: number;
  error?: string;
}
export async function post(base: string, key: string, path: string, body: unknown,
  valid: (value: unknown) => boolean, closeConnection = false): Promise<HttpResult> {
  const started = performance.now();
  try {
    const response = await fetch(`${base}${path}`, {
      method: 'POST',
      headers: {
        authorization: `Bearer ${key}`, 'content-type': 'application/json',
        ...(closeConnection ? { connection: 'close' } : {}),
      },
      body: JSON.stringify(body),
    });
    const text = await response.text();
    let parsed: unknown;
    try { parsed = text ? JSON.parse(text) : undefined; } catch { parsed = undefined; }
    const error = response.status !== 200 ? `HTTP ${response.status}` : !valid(parsed) ? 'invalid response' : undefined;
    return { status: response.status, latencyMs: performance.now() - started, ...(error ? { error } : {}) };
  } catch (err) {
    return { status: 0, latencyMs: performance.now() - started, error: `fetch ${err instanceof Error ? err.name : 'Error'}` };
  }
}

export function percentile(sorted: readonly number[], fraction: number): number {
  if (!sorted.length) return 0;
  return sorted[Math.min(sorted.length - 1, Math.ceil(fraction * sorted.length) - 1)]!;
}

interface QueryResult { rows: Array<Record<string, unknown>> }
export interface AdminClient {
  connect(): Promise<void>;
  query(text: string, values?: unknown[]): Promise<QueryResult>;
  end(): Promise<void>;
}
interface PgClientConstructor { new(options: { connectionString: string }): AdminClient }

export function databaseUrl(): string {
  const value = process.env.TEST_DATABASE_URL;
  if (!value) throw new Error('TEST_DATABASE_URL is required for PostgreSQL mode');
  return value;
}

export function adminClient(): AdminClient {
  const require = createRequire(new URL('../../packages/pdp-http/package.json', import.meta.url));
  const { Client } = require('pg') as { Client: PgClientConstructor };
  return new Client({ connectionString: databaseUrl() });
}

export async function resetDatabase(): Promise<void> {
  const client = adminClient();
  await client.connect();
  try {
    await client.query('DROP TABLE IF EXISTS gate_doc, gate_audit, gate_audit_meta, gate_anchor, gate_audit_segment, gate_subject_identity, gate_sync, gate_token, gate_performed, gate_session, gate_blp_mark, gate_blp_session, gate_retired, gate_subject, gate_resource, gate_tuple, gate_state_change, gate_rate_limit');
    await client.query(SCHEMA);
  } finally {
    await client.end();
  }
}
